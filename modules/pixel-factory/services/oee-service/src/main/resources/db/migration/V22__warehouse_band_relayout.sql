-- P32: 창고동을 "빗(comb)" 구조로 전면 재설계 — 좌우 세로 스파인 + 밴드 12개(밴드마다
-- 자체 통로 + 렉 2행) + 렉 864기(4열×3행×3층이던 72기에서 교체). 설계 근거:
-- docs/p32-warehouse-realistic-relayout-design.md.
--
-- **왜 912가 아니라 864인가.** 문서 D2의 예시(밴드12×행2×열38=912)는 "출발점이지 확정치가
-- 아니다"라고 명시돼 있다. 실제 렉 발자국(대시보드 `RackShape`, 새 밀도용 'VD' 방향 1.0×1.6)
-- 기준으로 커넥터 클리어런스(≥1.75)를 지키며 기존 창고동 폭(스파인 간 50유닛, 건물 폭 53 안)
-- 에 넣을 수 있는 최대 열 수는 36이었다 — 그래서 12×2×36=864. 이 조정 덕분에 **다른 건물
-- (PROD/QC/신관)의 x좌표·`layout_settings.width`는 전혀 안 건드린다** — 세로(y)만 커진다.
--
-- **왜 새 렉 방향(orientation='VD')이 필요한가.** 기존 'V'(1.6×4.4)/'H'(4.6×1.6) 발자국은
-- P28~P30의 성긴 배치(렉 72기)를 위한 고정 크기다. 참고 이미지 수준의 밀집 그리드를 만들려면
-- 훨씬 작은 발자국이 필요해서, 대시보드 `RackShape`에 밀집 전용 방향을 추가한다(기존 'V'/'H'
-- 렉— 2·3층 포함 — 은 크기·동작 전혀 안 바뀐다. 이번 파일은 하위호환 추가일 뿐이다).
--
-- **왜 게이트(`WH-GATE-U`/`WH-GATE-L`) 좌표가 안 바뀌는가.** 우측 스파인을 밴드 진입
-- 노드 12개를 y순으로 잇는 수직 체인으로 만들고, 그 체인에 y=9·y=18인 지점(기존 게이트
-- y값과 정확히 같다)을 접속 노드로 끼워 넣었다 — 스파인이 연속이므로 원래 게이트 좌표를
-- 그대로 접점으로 재사용할 수 있다(D1 "계약 유지" 요구사항).
--
-- **왜 창고동 2·3층은 이 파일에서 안 건드리는가(D5 권장 A).** `LocationRegistry` 조사
-- 결과 2·3층 렉은 1층과 좌표가 겹칠 뿐 완전히 독립된 데이터라, 1층만 바꿔도 물리적으로
-- 충돌하지 않는다. 2·3층을 없애는 건 그 자체로 또 다른 마이그레이션이라 이번 스코프 밖.
-- `WH-ELEV-1F`도 같은 이유로 **좌표(30,13)를 그대로 유지**한다 — 샤프트가 수직으로
-- 2·3층과 같은 자리를 관통해야 하므로, 새 그래프에 연결 엣지만 새로 단다.
--
-- **왜 `WH-SHIP-2`(P30)를 없애는가.** P30에서 이 노드를 만든 이유는 "실제 주문이 지나가는
-- 명명 노드가 필요해서"였다(P29 0-2절 — 렉은 LaneGraph를 안 타므로 명명 노드 없인 순환
