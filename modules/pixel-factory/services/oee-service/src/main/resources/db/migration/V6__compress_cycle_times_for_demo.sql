-- 표준 사이클타임을 데모 시계에 맞춘다 (10배 압축).
--
-- **왜:** 시뮬레이터가 SIM_SPEED=10 으로 "30초 사이클"이라면서 3초마다 발행하고 있었다.
-- OEE는 실시간(occurred_at)으로 계산하므로, 실시간 기준으로는 표준CT가 허용하는 양의 10배를
-- 낸 셈이 되어 **P가 250~650% 로 나왔다**(performanceAnomaly 플래그가 정상적으로 떴다).
-- 엔진 버그가 아니라 시뮬레이터와 지표의 시간 기준이 어긋난 것이었다.
--
-- **선택:** 데모 공장을 "빠른 공장"으로 정의한다. 표준CT를 1/10로 줄이고 시뮬레이터도 같은
-- 값을 쓰며 배속(SIM_SPEED)은 1로 둔다. 시계가 하나가 되므로 P ≈ 1 이 되고, 지도의 활기는
-- 그대로다(발행 주기가 지금과 같다).
--
-- **대가:** 설비 스펙이 "CNC 선반 3초 사이클"로 비현실적이다. 시간을 압축한 데모라는 뜻이며,
-- 실제 공장 값으로 돌리려면 이 마이그레이션 값과 시뮬레이터 EQUIPMENTS 를 10배로 되돌리고
-- SIM_SPEED 를 빼면 된다(그러면 사이클이 30초가 되어 화면이 한참 조용해진다).
--
-- 시뮬레이터의 EquipmentSpec 값과 **반드시 일치해야 한다** — 어긋나면 P가 그 비율만큼 틀어진다.

update equipments set ideal_cycle_time_ms = ideal_cycle_time_ms / 10, updated_at = now();
