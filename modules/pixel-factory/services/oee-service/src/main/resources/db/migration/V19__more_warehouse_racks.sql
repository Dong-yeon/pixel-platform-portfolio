-- P28: 창고동 렉 밀도를 2배로 — 3열×3행(9기/층) → 6열×3행(18기/층).
--
-- **왜.** V16이 창고동 폭을 40으로 넓히면서 통로만 벌리고 렉은 3열 그대로 뒀다 —
-- 연결로(4/17/30) 사이 "베이"마다 빈 칸이 폭 13유닛인데 렉 1열(폭 1.6)만 서 있어
-- 시각적으로 휑하다. 이번엔 베이마다 렉을 2열로 늘린다.
--
-- **기존 27기는 코드를 안 바꾸고 자리만 옮긴다.** WMS는 렉의 좌표를 전혀 모른다(코드
-- 문자열로만 결합, 설계 근거: docs/p23-pallet-unit-design.md) — 좌표 이동은 WMS
-- 마이그레이션이 필요 없다. 기존 재고·안전재고 시드(P26)가 전부 그대로 유효하다.
-- 새 27기(R10~R18)는 완전히 새 코드라 WMS 쪽엔 별도 마이그레이션(V9)으로 로케이션을
-- 추가한다.
--
-- 베이 경계(연결로 x)에서 1.75 이상 띄운다는 V12 규칙을 그대로 지킨다 — 실측 간격은
-- 전부 2.5~4.0으로 더 여유 있다. 행(y=4.0/13.5/22.0)은 V16 이후 한 번도 안 바뀐 값이라
-- 통로·벽 간격이 이미 검증돼 있으므로 그대로 재사용한다(설계 근거:
-- docs/p28-warehouse-rack-density-design.md D1).

